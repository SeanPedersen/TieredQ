"""Issue #13: generate src/tieredq_additive_books.h from the fitted part tables. Usage: gen_header.py BEST.json SEVEN.json OUT.h"""
import json
import sys

import numpy as np

WIDEST_PART_FIRST = {5: (4, 1), 6: (4, 2), 8: (4, 4)}


def literals(values):
    return ",".join(f"{float(np.float32(value)):.9g}f" for value in values)


def centered(parts):
    """Moves every part's midrange into the first part: sums keep their value and byte tables their full signed range."""
    parts = [np.array(part) for part in parts]
    for i in range(1, len(parts)):
        middle = (parts[i].min() + parts[i].max()) / 2
        parts[i] = parts[i] - middle
        parts[0] = parts[0] + middle
    return parts


def main(best_path, seven_path, out_path):
    best = json.load(open(best_path))
    seven = json.load(open(seven_path))
    books = {7: (seven["part_bits"], seven["parts"], seven["distortion"], seven["lloyd"])}
    for bits, widths in WIDEST_PART_FIRST.items():
        book = best[str(bits)]
        a, b = sorted(book["a"]), sorted(book["b"])
        parts = (a, b) if len(a) == 1 << widths[0] else (b, a)
        books[bits] = (widths, parts, book["distortion"], book["lloyd"])
    books = {bits: (widths, centered(parts), distortion, lloyd) for bits, (widths, parts, distortion, lloyd) in books.items()}
    lines = ["// Generated by benchmark/experiments/issue13_additive/gen_header.py: Gaussian-fitted additive codebooks for 5-8 bit",
             "// tiers. A level is one entry per part summed, so a code scores as nibble-lookup parts of 1, 2 or 4 bits (#13).",
             "#pragma once", "#include <vector>", "", "namespace tq::tieredq_detail {",
             "struct AdditiveBookParts { std::vector<unsigned> bits; std::vector<std::vector<float>> levels; };",
             "inline const std::vector<AdditiveBookParts>& additive_book_parts() { // indexed by code width; empty below 5",
             "  static const std::vector<AdditiveBookParts> books{", "    {},{},{},{},{},"]
    for bits in sorted(books):
        widths, parts, distortion, lloyd = books[bits]
        lines.append(f"    // {bits} bits: distortion {distortion:.7f}, Lloyd-Max {lloyd:.7f}")
        lines.append("    {{" + ",".join(map(str, widths)) + "},{")
        lines += ["      {" + literals(part) + "}," for part in parts]
        lines.append("    }},")
    lines += ["  };", "  return books;", "}", "} // namespace tq::tieredq_detail", ""]
    open(out_path, "w").write("\n".join(lines))


if __name__ == "__main__":
    main(*sys.argv[1:])
