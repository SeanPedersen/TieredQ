"""Recover missing NPZ containers from intact cached arrays; never download or alter originals.

GloVe arrays and truth must match the archived issue #4 input hashes. SIFT's full corpus and test
queries come from the retained source HDF5; its missing exact truth is regenerated by the same harness.
"""
import hashlib
import json
from pathlib import Path
import sys

B=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(B))
import numpy as np
import h5py
from data import ground_truth, verify_checksum, SOURCES
from threadpoolctl import threadpool_limits

w=Path(sys.argv[1]).resolve()
out=w/'recovered-cache'
out.mkdir(exist_ok=True)
source=Path.home()/'experiments/TieredQ-issue20-ship-20261029/data/glove'
expected=json.loads((B/'results/issue4-final-20261029/inputs.json').read_text())['glove']
arrays={name:np.fromfile(source/f'{name}.{suffix}',dtype=dtype).reshape(-1,dim)
        for name,suffix,dtype,dim in [('base','f32',np.float32,200),('queries','f32',np.float32,200),
                                      ('truth','u32',np.uint32,10)]}
hashes={name:hashlib.sha256(a.tobytes()).hexdigest() for name,a in arrays.items()}
assert hashes==expected,(hashes,expected)
assert arrays['base'].shape==(100000,200) and arrays['queries'].shape==(1000,200)
np.savez(out/'glove-100000-1000-v2.npz',**arrays)
provenance={'glove':dict(source=str(source),array_sha256=hashes,truth='reused byte-identical cached truth')}
path=Path.home()/'experiments/TieredQ-issue4-equal-memory-after-20261028/data/sift.hdf5'
verify_checksum(path,SOURCES['sift']['sha256'])
with h5py.File(path) as f:
    base=np.asarray(f['train'][:1000000],dtype=np.float32)
    queries=np.asarray(f['test'][:1000],dtype=np.float32)
with threadpool_limits(limits=8):
    truth=ground_truth(base,queries,True)
arrays=dict(base=base,queries=queries,truth=truth)
assert {k:hashlib.sha256(v.tobytes()).hexdigest() for k,v in arrays.items()} == json.loads(
    (B/'results/issue4-final-20261029/inputs.json').read_text())['sift']
np.savez(out/'sift-1000000-1000-v2.npz',**arrays)
provenance['sift']=dict(source=str(path),source_sha256=SOURCES['sift']['sha256'],
                       array_sha256={k:hashlib.sha256(v.tobytes()).hexdigest() for k,v in arrays.items()},
                       truth='regenerated exact FP32 top-10 with current unchanged top-10 algorithm')
(w/'recovered-data-provenance.json').write_text(json.dumps(provenance,indent=2))
print('Recovered GloVe byte-identically; regenerated missing SIFT container from verified cached HDF5',flush=True)
